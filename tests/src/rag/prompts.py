def build_grouped_context(docs, block_label: str = "후보") -> str:
    """청크들을 약품명 기준으로 묶어서 사람이 읽기 좋은 블록으로 만든다."""
    grouped: dict[str, list[str]] = {}
    for doc in docs:
        name = doc.metadata.get("item_name", "알수없음")
        grouped.setdefault(name, []).append(doc.page_content)

    blocks = []
    for i, (name, texts) in enumerate(grouped.items(), start=1):
        block = f"[{block_label} {i}: {name}]\n" + "\n".join(f"- {t}" for t in texts)
        blocks.append(block)
    return "\n\n".join(blocks)


