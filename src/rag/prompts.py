def build_context(docs) -> str:
    lines = [f"{i}. {doc.page_content}" for i, doc in enumerate(docs, start=1)]
    return "\n".join(lines)


def build_user_prompt(question: str, context: str) -> str:
    return f"[참고 자료]\n{context}\n\n[질문]\n{question}"